@pytest.mark.parametrize(
    ("mutation", "expected"),
    [
        (
            lambda records: records[4]["test_plan"].update(
                resource_changes=[
                    {"address": "google_storage_bucket.bad", "change": {"actions": ["create"]}}
                ]
            ),
            "managed-resource entries",
        ),
        (
            lambda records: records.append(
                {"type": "test_state", "test_state": {}}
            ),
            "prohibited event",
        ),
        (
            lambda records: records[0].update(terraform="9.9.9"),
            "version or abstract",
        ),
        (
            lambda records: records[1].update(test_abstract={"evil.tftest.hcl": ["evil"]}),
            "version or abstract",
        ),
        (
            lambda records: records[4].update(test_plan={}),
            "metadata is not exact",
        ),
        (
            lambda records: records.insert(
                4,
                {
                    "type": "test_run",
                    "@testfile": "evil.tftest.hcl",
                    "@testrun": "evil",
                    "test_run": {
                        "path": "evil.tftest.hcl",
                        "run": "evil",
                        "progress": "starting",
                    },
                },
            ),
            "run events are not exactly bound",
        ),
    ],
)
def test_inert_test_parser_rejects_non_inert_evidence(mutation, expected: str) -> None:
    records = _passing_test_records()
    mutation(records)
    with pytest.raises(ValueError, match=expected):
        parse_quebec_test_json("\n".join(json.dumps(record) for record in records))


def test_generated_provider_lock_requires_exact_version_and_signed_hashes(
    tmp_path: Path,
) -> None:
    lock = tmp_path / ".terraform.lock.hcl"
    lock.write_text(GENERATED_LOCK, encoding="utf-8")
