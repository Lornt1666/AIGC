def test_canonical_ci_initializes_tests_and_plans_quebec_root() -> None:
    contract = _contract()
    stage_ids = [stage["id"] for stage in contract["stages"]]
    assert contract["schema_version"] == "1.2.0"
    assert stage_ids == EXPECTED_STAGES
    stage = next(
        stage
        for stage in contract["stages"]
        if stage["id"] == "quebec_terraform_validate"
    )
    assert stage["policy"]["committed_provider_lock_required"] is True
    assert stage["policy"]["native_terraform_test_required"] is True
    assert stage["policy"]["zero_managed_resource_changes_required"] is True
    assert stage["policy"]["machine_readable_test_plan_required"] is True
    assert stage["policy"]["isolated_in_memory_test_state_required"] is True
    assert stage["policy"]["test_state_event_forbidden"] is True
    assert stage["policy"]["all_test_assertion_runs_pass_required"] is True
    assert stage["policy"]["backend_initialization_permitted"] is False
    assert stage["policy"]["external_action_permitted"] is False
    commands = quebec_terraform_commands(lockfile_readonly=True)
    assert stage_commands(
        stage,
        lockfile_readonly=True,
    ) == commands

    rendered = [" ".join(command) for command in commands]
    assert rendered == [
        "terraform -chdir=infra/gcp/quebec fmt -check -recursive",
        (
            "terraform -chdir=infra/gcp/quebec init -backend=false "
            "-input=false -no-color -lockfile=readonly"
        ),
        "terraform -chdir=infra/gcp/quebec validate -json",
        (
            "terraform -chdir=infra/gcp/quebec test "
            "-test-directory=ci/tftest "
            "-filter=ci/tftest/inert_authority.tftest.hcl "
            "-json -verbose -no-color"
        ),
    ]


